import { create } from 'zustand';
import { startSyncDiagnostics, finishSyncDiagnostics, recordSyncTransfer } from './diagnostics';
import { getSyncMetrics, resetSyncMetrics } from './metrics';
import { createSyncProgress, initialSyncProgress } from './progressCore';
import type { HistoryProgress } from './replay';
export type { SyncPhase } from './progressCore';
export const useGoogleSyncProgress = create(initialSyncProgress);
const progress = createSyncProgress({get:useGoogleSyncProgress.getState,set:value=>useGoogleSyncProgress.setState(value)}, {startDiagnostics:startSyncDiagnostics,finishDiagnostics:finishSyncDiagnostics,resetMetrics:resetSyncMetrics,getMetrics:getSyncMetrics,recordTransfer:recordSyncTransfer});
export const withSyncProgress = progress.withSyncProgress;
export const syncStage = progress.syncStage;
export const phaseProgress = progress.phaseProgress;
export const syncPhase = progress.syncPhase;
export const syncHistoryProgress = (value: HistoryProgress) => progress.syncHistoryProgress(value);
export const completedFile = progress.completedFile;
export const beginTransfer = progress.beginTransfer;
