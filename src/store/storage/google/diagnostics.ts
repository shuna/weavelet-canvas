import { create } from 'zustand';
import { createSyncDiagnostics, initialSyncDiagnostics, summarizeHistory, type Compaction, type HistoryObservation, type SyncDiagnostics, type TransferPurpose } from './diagnosticsCore';
import type { SyncMetrics } from './metricsCore';
export { summarizeHistory, type Compaction, type HistoryObservation, type TransferPurpose } from './diagnosticsCore';
export const useGoogleSyncDiagnostics = create<SyncDiagnostics>(() => initialSyncDiagnostics());
const diagnostics = createSyncDiagnostics({get:useGoogleSyncDiagnostics.getState,set:value=>useGoogleSyncDiagnostics.setState(value)});
export const startSyncDiagnostics = diagnostics.start;
export const finishSyncDiagnostics = (result:'completed'|'failed',elapsedMs:number,metrics:SyncMetrics) => diagnostics.finish(result,elapsedMs,metrics);
export const recordSyncTransfer = diagnostics.transfer;
export const recordPackAccess = diagnostics.packAccess;
export const reportSyncHistory = diagnostics.history;
export const reportCompaction = diagnostics.compaction;
