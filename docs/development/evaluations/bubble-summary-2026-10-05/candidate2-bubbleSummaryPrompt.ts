- 物語や作業の状態変化は、後続に必要な現在状態と因果関係を保ってください。古い例示や候補を、現在の設定や合意として混ぜないでください。
- 対象が会話の途中から始まる可能性があります。欠けた前提や参照を埋めず、対象内で確認できない点を必要なら短く明記してください。
- 有効な指示、現在状態、未解決事項を分ける見出しは必要な場合にだけ使ってください。発言者別の履歴一覧を機械的に作らないでください。

