export function buildBubbleSummaryPrompt(messages: MessageInterface[]): string {
  const input = messages.map(message => ({
    role: message.role,
    content: message.content.filter(isTextContent).map(part => part.text).join('\n'),
  }));
  return `${input.length === 1 ? singlePrompt : continuousPrompt}INPUT:\n${JSON.stringify(input.length === 1 ? input[0] : input)}`;
}
